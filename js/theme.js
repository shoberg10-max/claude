// 配色テーマ（プレビューHTML/CSSとPPTX書き出しの両方で共有する単一ソース）
//
// NRI（野村総合研究所）が経済産業省向けに作成した報告書PDF（2024FY/000700, 2023FY/000283）
// から実際に使われている色をピクセル単位で抽出し、そのまま採用している。
//
// 基本方針：青の濃淡とグレーで差をつけ、オレンジ・レッドは「本当に強調したい1点だけ」に
// 使う予約色とする（多用しない）。
// 青は「ネイビー → ミディアム → 中間 → ライト → ソフト → 淡 → 極淡」の7段階を用意している。
// 入れ子シェブロンや段階的に濃くなる帯、円弧サイクルなど、同系色を並べて階層や順序を
// 表す図では、隣り合う段が識別できるだけの階調数が要るため。
//   - ネイビー #000F78 … タイトルバー・見出し文字・番号・矢印・罫線（基本色）
//   - ミディアムブルー #3C64AA … 2番目の階調（補助的な強調・2番目の系列など）
//   - 中間ブルー #6C8CC9 … 3番目の階調（円弧矢印・入れ子シェブロンの外帯）
//   - ライトブルー #7B9BC7 … 4番目の階調（表・チャートの塗り分けなど）
//   - ソフトブルー #9DB4DC … 5番目の階調（帯を段階的に薄くするときの中間）
//   - グレー #8C97A6 … 「他と違う／注意」を色相を変えずに示す（オレンジ・レッドの代わり）
//   - オレンジ #F59637 ／ レッド #C0392B … 予約色。推奨案・リスクなど、本当に一点だけ
//     強調したい箇所にのみ使う（`highlight` / `critical`）。
window.DocAssist = window.DocAssist || {};

DocAssist.theme = {
  primary: '000F78',      // ネイビー（基本色）
  primaryLight: '3C64AA', // ミディアムブルー（第2階調）
  mid: '6C8CC9',          // 中間のブルー（第3階調。円弧矢印・入れ子シェブロンの外帯など）
  accent: '7B9BC7',       // ライトブルー（第4階調）
  softBlue: '9DB4DC',     // やわらかいブルー（第5階調。段階的に薄くする帯の中間）
  accent2: '5A63A7',      // ネイビーより明るい青紫（補助テキスト・軽い強調）
  gray: '8C97A6',         // グレー（注意・区別を色相を変えずに示す）
  highlight: 'F59637',    // オレンジ（予約色。推奨案など本当に一点だけ強調したい箇所に）
  critical: 'C0392B',     // レッド（予約色。リスク・警告など、より強い注意喚起が必要な場合に）
  positive: '000F78',     // 増加・強み・機会など「ポジティブ」の意味づけ（ネイビー）
  negative: '8C97A6',     // 減少・弱み・脅威など「注意」の意味づけ（グレー。オレンジ/レッドは使わない）
  light: 'D6DFF0',        // コンテンツボックスの塗り（ライトブルー）
  lighter: 'EDF1FA',      // さらに淡いブルー（テーブルの縞模様等）
  pale: 'F5F7FC',         // ほぼ白に近い青（象限の塗り分けなど、最も淡い階調）
  paleGray: 'ECECEC',     // ほぼ白に近いグレー（象限で1つだけ色相を外したいとき）
  border: 'BFBFBF',       // 罫線（グレー、控えめに使用）
  text: '000000',         // 本文（黒）
  subtext: '595959',      // 出所表記・ページ番号等の小さいグレー文字
  white: 'FFFFFF',
  fontFace: 'Yu Gothic UI', // 全テキストに使うフォント（js/pptxExport.jsのwithDefaultFontが参照）
  bulletChar: '■',          // 本文の箇条書きマーカー（js/patterns.jsのsquareBullet()とCSSの--bullet-charが参照）
};

// テンプレート読み込み機能（js/pptxImport.js）が配色・フォント・箇条書き記号を
// 上書きしたあと、「既定に戻す」で元のNRI配色に復元するためのスナップショット。
// DocAssist.theme のプロパティは各所で参照渡しされている（buildPptx等が呼び出しの
// たびに DocAssist.theme を読み直す設計）ため、テーマの切り替えはオブジェクトの
// 差し替えではなく、このスナップショットを使ったプロパティの上書き・復元で行う。
DocAssist.defaultTheme = Object.assign({}, DocAssist.theme);
