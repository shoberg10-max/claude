// NRI（野村総合研究所）が経済産業省向けに作成した報告書PDF（2024FY/000700, 2023FY/000283）
// から実際に使われている色をピクセル単位で抽出し、そのまま採用している。
//   - ネイビー #000F78 … タイトルバー・見出し文字・番号バッジ・矢印・罫線
//   - ライトブルー #D6DFF0 … コンテンツボックスの塗り（枠線なしで色面として使う）
//   - オレンジ #F59637 … 強調・ハイライト用のワンポイントアクセント（多用しない）
// 本文は黒、薄い罫線はグレーというシンプルな3色構成。
window.DocAssist = window.DocAssist || {};

DocAssist.theme = {
  primary: '000F78',      // ネイビー（タイトルバー・見出し・番号バッジ・矢印）
  primaryLight: '3C64AA', // ミディアムブルー（補助的な強調・2番目の系列など）
  accent: 'F59637',       // オレンジ（ワンポイントの強調・ハイライト）
  accent2: '5A63A7',      // ネイビーより明るい青紫（補助テキスト・軽い強調）
  positive: '000F78',     // 増加・強み・機会など「ポジティブ」の意味づけ（ネイビー）
  negative: 'F59637',     // 減少・弱み・脅威など「注意」の意味づけ（オレンジ）
  light: 'D6DFF0',        // コンテンツボックスの塗り（ライトブルー）
  lighter: 'EDF1FA',      // さらに淡いブルー（テーブルの縞模様等）
  border: 'BFBFBF',       // 罫線（グレー、控えめに使用）
  text: '000000',         // 本文（黒）
  subtext: '595959',      // 出所表記・ページ番号等の小さいグレー文字
  white: 'FFFFFF',
};
