// 配色テーマ（プレビューHTML/CSSとPPTX書き出しの両方で共有する単一ソース）
//
// NRI（野村総合研究所）が経済産業省向けに作成した報告書PDF（2024FY/000700, 2023FY/000283）
// から実際に使われている色をピクセル単位で抽出し、そのまま採用している。
//
// 基本方針：青の濃淡とグレーで差をつけ、オレンジ・レッドは「本当に強調したい1点だけ」に
// 使う予約色とする（多用しない）。
//   - ネイビー #000F78 … タイトルバー・見出し文字・番号バッジ・矢印・罫線（基本色）
//   - ミディアムブルー #3C64AA … 2番目の階調（補助的な強調・2番目の系列など）
//   - ライトブルー #7B9BC7 … 3番目の階調（表・チャートの塗り分けなど）
//   - グレー #8C97A6 … 「他と違う／注意」を色相を変えずに示す（オレンジ・レッドの代わり）
//   - オレンジ #F59637 ／ レッド #C0392B … 予約色。推奨案・リスクなど、本当に一点だけ
//     強調したい箇所にのみ使う（`highlight` / `critical`）。
window.DocAssist = window.DocAssist || {};

DocAssist.theme = {
  primary: '000F78',      // ネイビー（基本色）
  primaryLight: '3C64AA', // ミディアムブルー（第2階調）
  accent: '7B9BC7',       // ライトブルー（第3階調）
  accent2: '5A63A7',      // ネイビーより明るい青紫（補助テキスト・軽い強調）
  gray: '8C97A6',         // グレー（注意・区別を色相を変えずに示す）
  highlight: 'F59637',    // オレンジ（予約色。推奨案など本当に一点だけ強調したい箇所に）
  critical: 'C0392B',     // レッド（予約色。リスク・警告など、より強い注意喚起が必要な場合に）
  positive: '000F78',     // 増加・強み・機会など「ポジティブ」の意味づけ（ネイビー）
  negative: '8C97A6',     // 減少・弱み・脅威など「注意」の意味づけ（グレー。オレンジ/レッドは使わない）
  light: 'D6DFF0',        // コンテンツボックスの塗り（ライトブルー）
  lighter: 'EDF1FA',      // さらに淡いブルー（テーブルの縞模様等）
  border: 'BFBFBF',       // 罫線（グレー、控えめに使用）
  text: '000000',         // 本文（黒）
  subtext: '595959',      // 出所表記・ページ番号等の小さいグレー文字
  white: 'FFFFFF',
};
