//
// 直接APIを呼ぶのが難しい社内LLM環境でも使えるように、次の運用を想定している。
//   1. Step 1でこのプロンプトを生成してコピー
//   2. 社内LLMのチャット画面に貼り付けて実行
//   3. 出力された構成案テキストをコピーし、Step 1の入力欄に貼り付け直す
//   4. 「次へ」でこのアプリのパーサー(js/outline.js)に確実にはまる形で読み込む
//
// 出力フォーマットは、このアプリが前提とする「ヘッダー（パンくず）→メッセージ（リード文＋
// サブリード文の箇条書き）→ボディ（図表）→フッター（出所）」という、NRIの官公庁向け報告書の
// 実物から抽出した4層構成に対応している。
//   - "## [pattern: パターンID] 見出し" … パンくず形式の見出し＋推奨デザインパターン（js/outline.js が検出）
//   - "> リード文"                        … 結論・示唆を一文で言い切るメッセージ（js/outline.js が検出）
//   - ">> サブリード文"                    … リード文を補足する箇条書き（複数行可。1行=1項目として
//                                         ボディの図表の上に■マーカー付きで表示される。任意）
//   - "- 箇条書き"                        … メッセージの根拠となる詳細情報（ボディに描画される）
//   - "出所：◯◯"                         … その根拠データの出典（任意。フッターに表示される）
//   - "**語句**"                          … 文中で特に強調したい語句（太字＋ネイビーで表示される）
//   - "★" / "★推奨"                     … 比較系パターンで「この項目を推奨案として強調する」印
//                                         （多用しないための予約色トリガー。本当に1点だけに使う）
//
// 資料全体は、ストーリー型（デフォルトは「背景・目的の説明→論点を比較軸で整理→推奨案の提案→
// 意思決定→アクションプラン」）に沿って組み立てるよう、このプロンプト内で明示的に指示している。
// ストーリー型は STORY_TYPES から選べる（SCQA法／課題・原因・解決策／ピラミッド構造／PREP法など、
// 定番のコンサル資料構成フレームに対応）。
//
// また、資料の元ネタとなる会議メモ自体がまだ薄い場合に備え、テーマを深掘りするための
// buildDeepDivePrompt（型1〜3）も用意している。想定する使い方は次の3段階。
//   Step 0（任意・このファイルのbuildDeepDivePrompt）: テーマを社内LLMで深掘りし、論点・根拠を厚くする
//   Step 1（buildOutlineFormatPrompt）                : 深掘り結果（または会議メモ）を、選んだストーリー型で構成案に整形する
//   Step 2以降（このアプリ本体）                        : 構成案を編集し、スライドごとにデザインパターンを決めて書き出す
