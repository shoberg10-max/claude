// 社内LLM（コピペで使う想定）に投げるための「構成案整形プロンプト」を組み立てる。
//
// 直接APIを呼ぶのが難しい社内LLM環境でも使えるように、次の運用を想定している。
//   1. Step 1でこのプロンプトを生成してコピー
//   2. 社内LLMのチャット画面に貼り付けて実行
//   3. 出力された構成案テキストをコピーし、Step 1の入力欄に貼り付け直す
//   4. 「次へ」でこのアプリのパーサー(js/outline.js)に確実にはまる形で読み込む
//
// 出力フォーマットは、このアプリが前提とする「ヘッダー（パンくず）→メッセージ（リード文＋
// サブメッセージ）→ボディ（図表）→フッター（出所）」という、NRIの官公庁向け報告書の実物から
// 抽出した4層構成に対応している。
//   - "## [pattern: パターンID] 見出し" … パンくず形式の見出し＋推奨デザインパターン（js/outline.js が検出）
//   - "> リード文"                        … 結論・示唆を一文で言い切るメッセージ（js/outline.js が検出）
//   - ">> サブメッセージ"                  … リード文を補足する一文（任意）
//   - "- 箇条書き"                        … メッセージの根拠となる詳細情報（ボディに描画される）
//   - "出所：◯◯"                         … その根拠データの出典（任意。フッターに表示される）
//   - "**語句**"                          … 文中で特に強調したい語句（太字＋ネイビーで表示される）
//   - "★" / "★推奨"                     … 比較系パターンで「この項目を推奨案として強調する」印
//                                         （多用しないための予約色トリガー。本当に1点だけに使う）
//
// 資料全体は「背景・目的の説明→論点を比較軸で整理→推奨案の提案→意思決定→アクションプラン」
// という、顧客に意思決定と次のアクションを促すストーリーラインで組み立てるよう、
// このプロンプト内で明示的に指示している。
window.DocAssist = window.DocAssist || {};

(function () {
  function buildOutlineFormatPrompt(rawNotes) {
    const patternList = (DocAssist.patterns || [])
      .map((p) => `- ${p.id}: ${p.name} — ${p.description}`)
      .join('\n');

    return [
      'あなたは官公庁向けの報告書・提案書を数多く手掛けてきたコンサルティングファーム',
      '（BCG、マッキンゼー、デロイト、NRI、アビーム等）の資料作成担当です。',
      '以下の「元の会議メモ」を、次回会議に向けた報告書・提案書レベルの構成案に整形してください。',
      '',
      '# 想定する資料のレベル感',
      '- 官公庁向け報告書・提案書として通用する情報量・粒度にする（簡素なプレゼン用サマリーにしない）',
      '- スライドはテキストヘビーを基本とし、具体的な数値・固有名詞・因果関係を交えて詳しく記述する',
      '- 各スライドは「結論を一文で言い切るメッセージ」→「その根拠を示すボディ（本文・図表）」という',
      '  ピラミッド構造（結論ファースト）で構成する',
      '',
      '# 資料全体の構成（ストーリーライン）',
      '資料の目的は、顧客に論点への意思決定をしてもらい、次のアクションを決めて動いてもらうことである。',
      'そのため、資料全体（スライドの並び）は必ず以下の流れで構成する（会議メモの内容から該当する',
      'スライドが作れない場合は、その段階を省略してよい。ただし可能な限りこの流れに沿わせること）。',
      '  1. 背景・目的：論点がなぜ今議論すべきなのか、背景と目的を説明する',
      '  2. 論点の整理：論点に関する事実を、いくつかの比較軸・観点で整理する',
      '     （単純な箇条書きではなく、比較表（comparison-table）・ボックス比較（box-compare）・',
      '     　縦型比較（compare-vertical）など、表やボックスを使った比較・整理パターンを積極的に使う）',
      '  3. 提案：整理した結果を踏まえ、どの案で進めるべきかを提案する',
      '     （比較系パターンの箇条書きの中で、推奨する項目の行頭に「★」または「★推奨」を付けると、',
      '     　その項目だけがハイライトされる。本当に推奨する1項目だけに使い、多用しない）',
      '  4. 意思決定の確認：顧客に合意・意思決定してもらう論点を明確に示す',
      '  5. アクションプラン：意思決定後、誰が・何を・いつまでに行うかを示す',
      '     （action-plan-table パターンを使う。箇条書きは「タスク｜担当｜期限」の形式（全角パイプ',
      '     　区切り）で書く。例：「要件定義を完了する｜山田｜2026年3月末」）',
      '',
      '# 出力フォーマット（厳守）',
      '- 1行目に「# 資料タイトル」の形式で資料全体のタイトルを1つだけ書く',
      '- タイトルの後は1行空けて、スライドごとに次の形式で書く（スライド内の各行の間に空行は入れない）',
      '  ## [pattern: パターンID] 見出し（パンくず形式も可。例：「（１）現状分析｜①課題認識」のように「｜」で区切って章立てを示してよい）',
      '  > リード文（このスライドの結論・示唆を、体言止めではなく一文で言い切る。30〜60字程度）',
      '  >> サブメッセージ（リード文を補足する一文。任意、省略可）',
      '  - 箇条書き1',
      '  - 箇条書き2',
      '  - 箇条書き3',
      '  出所：参照した統計・調査名など（任意。外部データを使った場合のみ）',
      '- スライドとスライドの間は必ず1行空ける',
      '- 箇条書きはメッセージの根拠となる情報を3〜8個程度、具体的に記述する（テキストヘビーを許容する）',
      '- 複数の案・項目を比較する内容は「項目名：説明」の形式で箇条書きにする（例：「A案：低コストだが導入までに6ヶ月を要する」）',
      '- 比較系パターンで推奨案を1つ示す場合は、その項目の行頭に「★推奨 」を付ける（例：「B案：★推奨 コストと機能のバランスが良い」）',
      '- 複合レイアウトのパターン（下記一覧の説明に「〜の形式」と書かれているもの）は、その形式どおりに箇条書きを書く',
      '  ・全角パイプ「｜」＝列・段階の区切り（例：action-plan-table は「タスク｜担当｜期限」、task-status-table は「タスク：担当｜状況｜期限」）',
      '  ・全角スラッシュ「／」＝1つのまとまりの中の並列要素（例：as-is-to-be は「As-Is：基幹システム／顧客DB」）',
      '  ・丸括弧「（）」＝直前の要素の補足（例：「顧客DB（Oracle）」は2行目に「Oracle」が入る）',
      '- 文中で特に強調したい語句（結論・数値・固有名詞など）は「**語句**」のように前後を「**」で囲む（多用しすぎず、本当に重要な箇所だけに使う）',
      '- パターンIDは下記の「デザインパターン一覧」の中から、そのスライドの内容に最もふさわしいものを1つ選んで [pattern: パターンID] の形式で見出しの直後に入れる（迷う場合は title-message にする）',
      '- 出力は上記フォーマットのテキストのみとし、説明文・前置き・コードブロックの```は一切つけない',
      '',
      '# デザインパターン一覧（IDと使いどころ）',
      patternList,
      '',
      '# 出力例',
      '# 新製品発売に向けた提案資料',
      '',
      '## [pattern: box-compare] （１）価格戦略｜①価格プランの比較検討',
      '> 機能とコストのバランスから、**プレミアムプラン**が費用対効果の観点で最も優位である',
      '>> 初期費用を含めた3年間の総保有コストで比較しても優位性は維持される',
      '- スタンダード：月額1,000円、基本機能のみで拡張性に乏しい',
      '- プレミアム：月額3,000円、全機能を利用可能で導入企業の**8割が選択**',
      '- エンタープライズ：月額要相談、専任サポート付きだが中小規模には過剰投資',
      '出所：自社調べ（2026年1月時点の導入企業アンケート）',
      '',
      '## [pattern: box-compare] （２）発売時期の検討｜①タイミング案の比較',
      '> 競合動向とベータ検証期間を踏まえると、**11月発売案**が最もリスクが低い',
      '- 9月発売：先行者優位を確保できるが、品質検証期間が不足するリスクが高い',
      '- 11月発売：★推奨 競合の発売時期と重ならず、1ヶ月の検証期間も確保できる',
      '- 来年1月発売：最も安全だが、年内の販売機会を逃す',
      '',
      '## [pattern: action-plan-table] （３）実行計画｜①発売までのアクションプラン',
      '> 11月発売に向け、以下のスケジュールで各タスクを実行する',
      '- 開発完了・社内受け入れテスト実施｜開発部　鈴木｜2026年9月末',
      '- ベータ版リリース・主要顧客50社への先行提供｜営業部　田中｜2026年10月末',
      '- 全国キャンペーン準備・正式発売｜マーケティング部　高橋｜2026年11月末',
      '',
      '# 元の会議メモ',
      rawNotes && rawNotes.trim() ? rawNotes : '(ここに会議メモ・議事録を貼り付けてください)',
    ].join('\n');
  }

  DocAssist.buildOutlineFormatPrompt = buildOutlineFormatPrompt;
})();
